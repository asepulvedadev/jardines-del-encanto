import assert from "node:assert/strict";
import test from "node:test";
import { GET, POST, PATCH } from "../apps/web/app/api/crm/[...path]/route.ts";
const id = "00000000-0000-4000-8000-000000000001";
function request(endpoint, method = "GET") {
  return {
    method,
    url: `https://jardines.example/api/crm/${endpoint}`,
    body: null,
    headers: new Headers({
      "content-type": "application/json",
      origin: "https://jardines.example",
    }),
    cookies: { get: () => undefined },
  };
}
test("Sara configuration and synthetic jobs use exact gateway routes", async () => {
  process.env.CRM_ORIGIN = "https://jardines.example";
  process.env.API_BASE_URL = "http://api:8000";
  const old = global.fetch;
  let calls = [];
  global.fetch = async (url, init) => {
    calls.push([url, init.method]);
    return Response.json({ ok: true });
  };
  try {
    for (const [path, method, handler] of [
      ["sara/config", "GET", GET],
      ["sara/config", "PATCH", PATCH],
      ["sara/config/versions", "GET", GET],
      ["sara/simulations", "POST", POST],
      [`sara/simulations/${id}`, "GET", GET],
    ]) {
      const response = await handler(request(path, method), {
        params: Promise.resolve({ path: path.split("/") }),
      });
      assert.equal(response.status, 200, path);
    }
    assert.equal(calls.length, 5);
    for (const path of ["sara/config/secret", "sara/simulations/anything"])
      assert.equal(
        (
          await GET(request(path), {
            params: Promise.resolve({ path: path.split("/") }),
          })
        ).status,
        404,
      );
  } finally {
    global.fetch = old;
  }
});
test("Image gateway permits bounded original/generated bytes, rejects unexpected MIME and query", async () => {
  process.env.CRM_ORIGIN = "https://jardines.example";
  process.env.API_BASE_URL = "http://api:8000";
  const old = global.fetch;
  let mime = "image/png";
  global.fetch = async () =>
    new Response(new Uint8Array([137, 80, 78, 71]), {
      headers: { "content-type": mime },
    });
  try {
    for (const path of [
      `images/${id}/content`,
      "images/assets/logo-white/content",
    ]) {
      const r = await GET(request(path), {
        params: Promise.resolve({ path: path.split("/") }),
      });
      assert.equal(r.status, 200);
      assert.equal(r.headers.get("content-type"), "image/png");
      assert.equal((await r.arrayBuffer()).byteLength, 4);
    }
    mime = "text/html";
    const path = `images/${id}/content`;
    assert.equal(
      (
        await GET(request(path), {
          params: Promise.resolve({ path: path.split("/") }),
        })
      ).status,
      502,
    );
    mime = "image/png";
    const req = request("images/catalog?url=evil");
    assert.equal(
      (
        await GET(req, {
          params: Promise.resolve({ path: ["images", "catalog"] }),
        })
      ).status,
      422,
    );
  } finally {
    global.fetch = old;
  }
});
